const SESSION_DISMISSED_AUDIT_KEY = 'wterm_dismissed_auto_audit_v1';

export function markAutoAuditDismissed(pairKey?: string) {
  try {
    if (!pairKey) {
      sessionStorage.setItem(SESSION_DISMISSED_AUDIT_KEY, '*');
    } else {
      const prev = sessionStorage.getItem(SESSION_DISMISSED_AUDIT_KEY) ?? '';
      if (prev === '*') return;
      const set = new Set(prev ? prev.split(',') : []);
      set.add(pairKey);
      sessionStorage.setItem(SESSION_DISMISSED_AUDIT_KEY, Array.from(set).join(','));
    }
  } catch {
    // ignore storage error
  }
}

export function clearAutoAuditDismissed() {
  try {
    sessionStorage.removeItem(SESSION_DISMISSED_AUDIT_KEY);
  } catch {
    // ignore
  }
}

function isAutoAuditDismissed(pairKey: string): boolean {
  try {
    const raw = sessionStorage.getItem(SESSION_DISMISSED_AUDIT_KEY);
    if (!raw) return false;
    if (raw === '*') return true;
    return raw.split(',').includes(pairKey);
  } catch {
    return false;
  }
}

/**
 * Global background signal collector & OKX evaluator.
 * Automatically captures signals generated by the Opciones de Trading engine
 * and continuously grades all tracked signals against real OKX candles,
 * regardless of which workspace tab is currently active.
 */
export function useAutoSignalTracker() {
  const asset = useTerminalStore((s) => s.asset);
  const timeframe = useTerminalStore((s) => s.timeframe);
  const candlesLength = useTerminalStore((s) => s.candles.length);
  const lastCandleTs = useTerminalStore((s) =>
    s.candles.length > 0 ? s.candles[s.candles.length - 1].t : 0
  );
  const candlesDatasetKey = useTerminalStore((s) => s.candlesDatasetKey);
  const marketMode = useTerminalStore((s) => s.scoringConfig.mode);

  const lastCaptureKeyRef = useRef<string>('');
  const autoAuditedPairsRef = useRef<Set<string>>(new Set());
  const scoringCacheRef = useRef<{
    key: string;
    fetchedAt: number;
    dataset: MultiTfScoringDataset;
  } | null>(null);

  // 1. Capture live signals + initial real walk-forward audit automatically whenever market data settles or a new candle bar opens
  useEffect(() => {
    const expectedKey = `${asset}|${timeframe}`;
    if (candlesDatasetKey !== expectedKey || candlesLength < 20 || lastCandleTs <= 0) {
      return;
    }

    let cancelled = false;
    const ctrl = new AbortController();

    async function captureAndEvaluateCurrentMarket() {
      const state = useTerminalStore.getState();
      if (state.candlesDatasetKey !== `${state.asset}|${state.timeframe}`) return;
      if (state.candles.length < 20) return;

      const latestCandle = state.candles[state.candles.length - 1];
      const spot = state.ticker?.idxPx ?? latestCandle?.c ?? 0;
      if (spot <= 0 || !latestCandle) return;

      const pairKey = `${state.asset}|${state.timeframe}|${state.scoringConfig.mode}`;

      // Refresh cached v1.1 scoring dataset if stale (>60s) or different asset/mode
      const scKey = `${state.asset}|${state.scoringConfig.mode}`;
      const cached = scoringCacheRef.current;
      let scoringDataset = cached && cached.key === scKey ? cached.dataset : null;
      if (!cached || cached.key !== scKey || Date.now() - cached.fetchedAt > 60_000) {
        try {
          const freshDs = await fetchScoringDataset(
            state.asset,
            state.scoringConfig.mode,
            ctrl.signal
          );
          if (cancelled) return;
          scoringDataset = freshDs;
          scoringCacheRef.current = {
            key: scKey,
            fetchedAt: Date.now(),
            dataset: freshDs,
          };
        } catch {
          // Non-fatal: still generate technical + liquidity signals
        }
      }

      if (cancelled) return;
      const freshState = useTerminalStore.getState();
      const activeCandles = freshState.candles;
      const currentSpot = freshState.ticker?.idxPx ?? activeCandles[activeCandles.length - 1]?.c ?? 0;
      const barTs = activeCandles[activeCandles.length - 1]?.t ?? 0;
      if (activeCandles.length < 20 || currentSpot <= 0 || barTs <= 0) return;

      const allStrikesAsc = aggregateStrikes(freshState.options, currentSpot, 'ALL');
      const optionsLevels = calculateLevels(allStrikesAsc, freshState.options, currentSpot);

      const expiryOptions = freshState.selectedExpiry
        ? freshState.options.filter((o) => o.expiry === freshState.selectedExpiry)
        : [];
      let cone = null;
      if (expiryOptions.length > 0 && expiryOptions[0].expTs > Date.now()) {
        const expStrikes = aggregateStrikes(expiryOptions, currentSpot, 'ALL');
        const expLevels = calculateLevels(expStrikes, expiryOptions, currentSpot);
        const atmIV = getAtTheMoneyIV(expiryOptions, currentSpot, freshState.selectedExpiry);
        cone = calculateExpectedRangeCone(
          currentSpot,
          atmIV,
          Date.now(),
          expiryOptions[0].expTs,
          freshState.selectedExpiry,
          expLevels.maxPain,
          24,
          expiryOptions
        );
      }

      const liquidity = analyzeMarketLiquidity(
        activeCandles,
        currentSpot,
        optionsLevels,
        freshState.orderbook,
        freshState.prevDayHigh,
        freshState.prevDayLow
      );

      const volumeProfile = calculateVolumeProfileBuckets(activeCandles.slice(-200), 36);
      const srZones = detectSupportResistanceZones(activeCandles, currentSpot);
      const fvgs = detectFairValueGaps(activeCandles, currentSpot, 6);
      const fibAnalysis = calculateFibonacciLevels(activeCandles, 120, 'auto', currentSpot, {
        anchorMode: 'pivots',
      });
      const deltaSeries = calculateVolumeDeltaSeries(activeCandles);
      const techSnapshot = computeTechnicalSnapshot(
        activeCandles,
        volumeProfile?.poc ?? liquidity.pocPrice,
        liquidity.imbalancePct
      );
      const divergences = detectOscillatorDivergences(
        activeCandles,
        techSnapshot.rsi14,
        techSnapshot.macd.hist,
        deltaSeries
      );
      const confluences = detectConfluenceZones({
        spot: currentSpot,
        srZones,
        fibAnalysis,
        volumeProfile,
        liquidityLevels: liquidity.levels,
        prevDayHigh: freshState.prevDayHigh,
        prevDayLow: freshState.prevDayLow,
      });

      const newsCorrelation = correlateNewsWithPriceAction(
        freshState.newsItems,
        freshState.newsCandles1h,
        freshState.events
      );
      const scoringResult = scoringDataset
        ? evaluateScoringSystem(scoringDataset, {
            ...freshState.scoringConfig,
            upcomingEvents: freshState.events,
          })
        : null;

      const ideas = generateTradingOptions({
        asset: freshState.asset,
        timeframe: freshState.timeframe,
        candles: activeCandles,
        spot: currentSpot,
        optionsLevels,
        cone,
        liquidity,
        capitalUsd: freshState.scoringConfig.capitalUsd,
        riskPct: freshState.scoringConfig.riskPct,
        scoring: scoringResult,
        spreadPct: freshState.orderbook?.spreadPct ?? 0.02,
        feePctPerSide: freshState.scoringConfig.feePctPerSide,
        slippagePctPerSide: freshState.scoringConfig.slippagePctPerSide,
        volumeProfile,
        fibAnalysis,
        fvgs,
        confluences,
        divergences,
        techSnapshot,
        macroRegime: {
          sentimentLabel: newsCorrelation.aggregateLabel,
          sentimentScore: newsCorrelation.aggregateScore,
          rollingR: null,
          windowDays: 30,
          volPct: null,
        },
      });

      const captureKey = `${pairKey}|${barTs}|${scoringResult ? 'v11' : 'base'}`;
      if (ideas.length > 0 && lastCaptureKeyRef.current !== captureKey) {
        lastCaptureKeyRef.current = captureKey;
        const incomingLive = ideas.map((idea) =>
          createTrackedSignalFromIdea(idea, {
            asset: freshState.asset,
            timeframe: freshState.timeframe,
            marketMode: freshState.scoringConfig.mode,
            candleOpenTs: barTs,
            spotAtSignal: currentSpot,
            origin: 'live',
          })
        );
        freshState.recordTrackedSignals(incomingLive);
      }

      // Auto-populate historical walk-forward baseline on real OKX candles once per pair if no audit exists yet
      const afterLiveState = useTerminalStore.getState();
      const hasPairAudit = afterLiveState.trackedSignals.some(
        (s) =>
          s.origin === 'audit' &&
          s.asset === afterLiveState.asset &&
          s.timeframe === afterLiveState.timeframe &&
          s.marketMode === afterLiveState.scoringConfig.mode
      );

      if (
        !hasPairAudit &&
        !autoAuditedPairsRef.current.has(pairKey) &&
        !isAutoAuditDismissed(pairKey) &&
        activeCandles.length >= 90
      ) {
        autoAuditedPairsRef.current.add(pairKey);
        const audited = auditHistoricalSignalsFromCandles({
          asset: afterLiveState.asset,
          timeframe: afterLiveState.timeframe,
          marketMode: afterLiveState.scoringConfig.mode,
          candles: activeCandles,
          horizonBars: DEFAULT_SIGNAL_HORIZON_BARS,
          stepBars: 8,
          capitalUsd: afterLiveState.scoringConfig.capitalUsd,
          riskPct: afterLiveState.scoringConfig.riskPct,
          optionsLevels,
        });
        if (audited.length > 0) {
          const merged = mergeSignalsIntoHistory(
            useTerminalStore.getState().trackedSignals,
            audited
          );
          useTerminalStore.getState().replaceTrackedSignals(merged);
        }
      }

      // Immediately re-evaluate tracked signals for the active pair against latest candles
      useTerminalStore
        .getState()
        .reevaluateTrackedSignals(
          freshState.asset,
          freshState.timeframe,
          freshState.scoringConfig.mode,
          activeCandles
        );
    }

    const timer = setTimeout(() => {
      void captureAndEvaluateCurrentMarket();
    }, 350);

    return () => {
      cancelled = true;
      ctrl.abort();
      clearTimeout(timer);
    };
  }, [asset, timeframe, candlesDatasetKey, candlesLength, lastCandleTs, marketMode]);

  // 2. Periodic background re-evaluation across ALL stored (asset, timeframe, marketMode) pairs every 30s
  useEffect(() => {
    let active = true;

    async function backgroundSyncAllPairs() {
      const state = useTerminalStore.getState();
      if (state.trackedSignals.length === 0) return;

      // Only fetch pairs that still have active/pending/TP1 signals OR differ from active live stream
      const pairMap = new Map<
        string,
        { asset: SymbolAsset; timeframe: Timeframe; mode: 'perpetual' | 'spot' }
      >();
      for (const sig of state.trackedSignals) {
        const key = `${sig.asset}|${sig.timeframe}|${sig.marketMode}`;
        if (!pairMap.has(key)) {
          pairMap.set(key, {
            asset: sig.asset,
            timeframe: sig.timeframe,
            mode: sig.marketMode,
          });
        }
      }

      const entries = Array.from(pairMap.entries());
      const candlesByPair = new Map<string, Candle[]>();

      // Reuse active in-memory candles for current active pair when compatible
      const activeKey = `${state.asset}|${state.timeframe}|${state.scoringConfig.mode}`;
      if (
        state.candlesDatasetKey === `${state.asset}|${state.timeframe}` &&
        state.candles.length >= 20
      ) {
        candlesByPair.set(activeKey, state.candles);
      }

      const pairsToFetch = entries.filter(([k]) => !candlesByPair.has(k)).slice(0, 4);
      if (pairsToFetch.length > 0) {
        const results = await Promise.allSettled(
          pairsToFetch.map(([, p]) =>
            fetchTechnicalMarketCandles(
              p.asset,
              p.timeframe,
              p.mode === 'perpetual' ? 'perp' : 'spot',
              300
            )
          )
        );
        if (!active) return;
        pairsToFetch.forEach(([key], idx) => {
          const res = results[idx];
          if (res.status === 'fulfilled' && res.value.length > 0) {
            candlesByPair.set(key, res.value);
          }
        });
      }

      const now = Date.now();
      const latestState = useTerminalStore.getState();
      let anyChanged = false;
      const updated = latestState.trackedSignals.map((sig) => {
        const key = `${sig.asset}|${sig.timeframe}|${sig.marketMode}`;
        const c = candlesByPair.get(key);
        if (!c || c.length === 0) return sig;
        const next = evaluateSignalAgainstCandles(sig, c, sig.horizonBars, now);
        if (
          next.status !== sig.status ||
          next.barsObserved !== sig.barsObserved ||
          next.lastPrice !== sig.lastPrice ||
          next.effectivenessPoints !== sig.effectivenessPoints
        ) {
          anyChanged = true;
        }
        return next;
      });

      if (anyChanged && active) {
        latestState.replaceTrackedSignals(updated);
      }
    }

    const intervalId = setInterval(() => {
      void backgroundSyncAllPairs();
    }, 30_000);

    return () => {
      active = false;
      clearInterval(intervalId);
    };
  }, []);
}
